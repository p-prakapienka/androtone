    inline Project createDefaultProject() {
        Project project;
        project.tempo = 80.0;
        project.tracks.resize(3);

        auto addClip = [&](int trackIndex, const auto& preset) {
            if (trackIndex >= static_cast<int>(project.tracks.size())) {
                return;
            }
            ProjectClip clip;
            clip.notes.assign(preset.begin(), preset.end());
            project.tracks[trackIndex].clips.push_back(std::move(clip));
        };

        addClip(0, kickStraight);
        addClip(0, kickHalfTime);
        addClip(1, strangerThingsBass);
        addClip(1, softBass);
        addClip(2, strangerThingsArp);
        addClip(2, softArp);

        return project;
    }
